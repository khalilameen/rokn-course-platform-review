'use strict';

const fs = require('fs');
const path = require('path');
const {execFileSync} = require('child_process');

const root = path.resolve(__dirname, '..');
const lockPath = path.join(root, 'ios', 'Podfile.lock');
const gemLockPath = path.join(root, 'Gemfile.lock');
const packagePath = path.join(root, 'package.json');
const packageLockPath = path.join(root, 'package-lock.json');
const failures = [];

const readJson = file => JSON.parse(fs.readFileSync(file, 'utf8'));
const fail = message => failures.push(message);
const versionAtLeast = (value, minimum) => {
  const parts = String(value || '')
    .split('.')
    .map(part => Number.parseInt(part, 10));
  const required = minimum.split('.').map(part => Number.parseInt(part, 10));
  for (let index = 0; index < required.length; index += 1) {
    const actual = Number.isFinite(parts[index]) ? parts[index] : 0;
    if (actual !== required[index]) return actual > required[index];
  }
  return true;
};
const toolVersion = value =>
  String(value || '').match(/(?:^|\s)(\d+\.\d+\.\d+)(?:\s|$)/)?.[1];

if (!fs.existsSync(lockPath)) {
  fail('ios/Podfile.lock is missing.');
}

const packageJson = readJson(packagePath);
const packageLock = readJson(packageLockPath);
const declaredReactNative = packageJson.dependencies?.['react-native'];
const lockedReactNative =
  packageLock.packages?.['node_modules/react-native']?.version;

let installedReactNative;
try {
  installedReactNative = require(path.join(
    root,
    'node_modules',
    'react-native',
    'package.json',
  )).version;
} catch {
  fail('node_modules/react-native is missing; run npm ci --include=dev first.');
}

if (declaredReactNative !== lockedReactNative) {
  fail(
    `package.json declares react-native ${declaredReactNative}, but ` +
      `package-lock.json resolves ${lockedReactNative || '<missing>'}.`,
  );
}
if (installedReactNative && installedReactNative !== lockedReactNative) {
  fail(
    `node_modules contains react-native ${installedReactNative}, but ` +
      `package-lock.json resolves ${lockedReactNative || '<missing>'}.`,
  );
}

const podVersions = new Map();
let lockedCocoaPods;
if (fs.existsSync(lockPath)) {
  const lock = fs.readFileSync(lockPath, 'utf8');
  lockedCocoaPods = lock.match(/^COCOAPODS: (\S+)$/m)?.[1];
  if (!lockedCocoaPods) fail('ios/Podfile.lock has no exact COCOAPODS version.');
  const podSection = lock.match(/^PODS:\r?\n([\s\S]*?)^DEPENDENCIES:/m)?.[1] || '';

  for (const line of podSection.split(/\r?\n/)) {
    const match = line.match(
      /^  - ([A-Za-z0-9_.+-]+)(?:\/[A-Za-z0-9_.+-]+)? \(([^)]+)\)/,
    );
    if (match && !podVersions.has(match[1])) {
      podVersions.set(match[1], match[2]);
    }
  }

  for (const corePod of ['React', 'React-Core']) {
    const podVersion = podVersions.get(corePod);
    if (podVersion !== lockedReactNative) {
      fail(
        `ios/Podfile.lock pins ${corePod} ${podVersion || '<missing>'}, but ` +
          `react-native is ${lockedReactNative || '<missing>'}.`,
      );
    }
  }
}

let bundledCocoaPods;
let lockedRuby;
let lockedBundler;
if (!fs.existsSync(gemLockPath)) {
  fail('Gemfile.lock is missing; CocoaPods must be executed through Bundler.');
} else {
  const gemLock = fs.readFileSync(gemLockPath, 'utf8');
  bundledCocoaPods = gemLock.match(/^    cocoapods \(([^)]+)\)$/m)?.[1];
  lockedRuby = gemLock.match(/^RUBY VERSION\r?\n\s+ruby ([0-9.]+)(?:p\d+)?$/m)?.[1];
  lockedBundler = gemLock.match(/^BUNDLED WITH\r?\n\s+([0-9.]+)$/m)?.[1];
  if (!bundledCocoaPods) {
    fail('Gemfile.lock has no exact CocoaPods resolution.');
  } else if (lockedCocoaPods && bundledCocoaPods !== lockedCocoaPods) {
    fail(
      `Gemfile.lock resolves CocoaPods ${bundledCocoaPods}, but ` +
        `ios/Podfile.lock was generated by ${lockedCocoaPods}.`,
    );
  }
  if (!lockedRuby || !versionAtLeast(lockedRuby, '3.2.0')) {
    fail(
      `Gemfile.lock must pin a maintained Ruby >=3.2.0; found ${lockedRuby || '<missing>'}.`,
    );
  }
  if (!lockedBundler || !versionAtLeast(lockedBundler, '2.5.0')) {
    fail(
      `Gemfile.lock must pin Bundler >=2.5.0; found ${lockedBundler || '<missing>'}.`,
    );
  }
}

if (process.platform === 'darwin' && lockedCocoaPods) {
  try {
    const runtimeRuby = execFileSync('ruby', ['-e', 'print RUBY_VERSION'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    }).trim();
    if (runtimeRuby !== lockedRuby) {
      fail(`ruby is ${runtimeRuby || '<missing>'}, but Gemfile.lock requires ${lockedRuby}.`);
    }
    const runtimeBundler = toolVersion(execFileSync('bundle', [`_${lockedBundler}_`, '--version'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    }));
    if (runtimeBundler !== lockedBundler) {
      fail(
        `bundle is ${runtimeBundler || '<missing>'}, but Gemfile.lock requires ${lockedBundler}.`,
      );
    }
    const xcodeVersion = execFileSync('xcodebuild', ['-version'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    })
      .match(/^Xcode (\S+)/m)?.[1];
    if (!xcodeVersion || !versionAtLeast(xcodeVersion, '26.2')) {
      fail(`Xcode >=26.2 is required; found ${xcodeVersion || '<missing>'}.`);
    }
    const runtimeCocoaPods = execFileSync(
      'bundle',
      [`_${lockedBundler}_`, 'exec', 'pod', '--version'],
      {
        cwd: root,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe'],
      },
    ).trim();
    if (runtimeCocoaPods !== lockedCocoaPods) {
      fail(
        `bundle exec pod is ${runtimeCocoaPods || '<missing>'}, but ` +
          `ios/Podfile.lock requires ${lockedCocoaPods}.`,
      );
    }
  } catch (error) {
    fail(
      `Could not verify the pinned Ruby/Bundler/Xcode/CocoaPods toolchain: ${String(
        error.stderr || error.message || 'unknown error',
      ).trim()}`,
    );
  }
}

const runJson = args => {
  try {
    const stdout = execFileSync(process.execPath, args, {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    return JSON.parse(stdout);
  } catch (error) {
    const detail = String(error.stderr || error.message || '').trim();
    fail(`Could not resolve iOS autolinking metadata: ${detail || 'unknown error'}`);
    return null;
  }
};

const expectedPods = new Set();
const reactNativeConfig = runJson([
  '--no-warnings',
  '--eval',
  "require('expo/bin/autolinking')",
  'expo-modules-autolinking',
  'react-native-config',
  '--json',
  '--platform',
  'ios',
]);

for (const dependency of Object.values(reactNativeConfig?.dependencies || {})) {
  const ios = dependency.platforms?.ios;
  if (!ios?.podspecPath) continue;

  const podspec = fs.readFileSync(ios.podspecPath, 'utf8');
  const literalName = podspec.match(
    /(?:s|spec)\.name\s*=\s*['"]([^'"]+)['"]/,
  )?.[1];
  const packageName = dependency.name;
  expectedPods.add(
    literalName ||
      (podspec.includes("package['name']") ? packageName : null) ||
      path.basename(ios.podspecPath, '.podspec'),
  );
}

const expoAutolinkingCli = path.join(
  root,
  'node_modules',
  'expo-modules-autolinking',
  'bin',
  'expo-modules-autolinking.js',
);
const expoModules = runJson([
  expoAutolinkingCli,
  'resolve',
  '--platform',
  'apple',
  '--project-root',
  root,
  '--json',
]);
for (const module of expoModules?.modules || []) {
  for (const pod of module.pods || []) {
    if (pod.podName) expectedPods.add(pod.podName);
  }
}

const missingPods = [...expectedPods]
  .filter(pod => !podVersions.has(pod))
  .sort((a, b) => a.localeCompare(b));
if (missingPods.length) {
  fail(`ios/Podfile.lock is missing autolinked pods: ${missingPods.join(', ')}.`);
}

if (failures.length) {
  console.error(`iOS dependency lock is stale or incomplete (${failures.length}):`);
  failures.forEach(item => console.error(`- ${item}`));
  console.error(
    '\nRegenerate it on macOS with exactly:\n' +
      '  npm ci --include=dev\n' +
      '  bundle install\n' +
      '  cd ios\n' +
      '  bundle exec pod install\n' +
      '  cd ..\n' +
      '  npm run verify:ios-lock\n\n' +
      'Then commit the generated ios/Podfile.lock. Do not edit Pod versions or ' +
      'checksums by hand.',
  );
  process.exit(1);
}

console.log(
  `iOS Podfile.lock matches react-native ${lockedReactNative} and ` +
    `${expectedPods.size} autolinked pods using CocoaPods ${lockedCocoaPods}.`,
);
